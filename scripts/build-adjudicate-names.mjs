#!/usr/bin/env node
/**
 * Generate workflows/adjudicate-names.js for the Pharmacopoeia blocks that would not align.
 *
 * What the job is, and why it is cheap. These monographs came out of OCR as two separate
 * column blocks: fifteen language labels, then a list of names, with no link between them
 * except order. Where the two lists are the same length, position is the link and
 * harvest-names-api.mjs resolves it. Where the name list is shorter, one or more languages
 * have no name for the drug and the gap is invisible positionally. Adhaki is the worked case:
 * fifteen labels, fourteen names, and the missing one is Kashmiri, so every name from
 * Kashmiri onward sits one row off and a Malayalam name would publish as Kashmiri.
 *
 * Finding the gap needs no retrieval, only the knowledge that Thuvara is Malayalam rather
 * than Kashmiri. So this pass is an order of magnitude cheaper per item than the Wikidata
 * corroboration run, which had to fetch a source per plant.
 *
 * Only records that map to one of our pages are included. An unmapped monograph's names have
 * nowhere to go, so adjudicating them would be work with no destination.
 *
 *   node scripts/build-adjudicate-names.mjs
 *   node scripts/build-adjudicate-names.mjs --per 14
 */
import fs from 'node:fs';
import path from 'node:path';

const IN = path.join('data', 'name-candidates-api.json');
const OUT = path.join('workflows', 'adjudicate-names.js');
const PER = (() => {
  const i = process.argv.indexOf('--per');
  return i === -1 ? 12 : Math.max(1, Number(process.argv[i + 1]));
})();

const payload = JSON.parse(fs.readFileSync(IN, 'utf8'));
const todo = payload.records
  .filter((r) => r.alignment === 'needsAdjudication' && r.page && r.values?.length)
  .map((r) => ({
    heading: r.heading,
    part: r.part,
    kind: r.page.kind,
    slug: r.page.slug,
    title: r.page.title,
    labels: r.labels.map((l) => l.lang),
    values: r.values,
  }))
  .sort((a, b) => a.slug.localeCompare(b.slug));

const batches = [];
for (let i = 0; i < todo.length; i += PER) {
  batches.push({ id: `a${String(batches.length + 1).padStart(2, '0')}`, records: todo.slice(i, i + PER) });
}

const script = `export const meta = {
  name: 'adjudicate-pharmacopoeia-names',
  description: 'Align Pharmacopoeia language labels to their name lists where OCR broke the link',
  phases: [
    { title: 'Align', detail: 'one agent per batch of monographs; each decides which languages have no name' },
  ],
}

/**
 * GENERATED by scripts/build-adjudicate-names.mjs. Do not hand-edit; regenerate.
 *
 * ${batches.length} batches, ${todo.length} monographs whose label and name lists are different lengths.
 *
 * No retrieval. The names are already the Pharmacopoeia's; the only question is which label
 * each one belongs to, and that is answered by recognising the language a name is in.
 */

const ALIGN_SCHEMA = {
  type: 'object',
  properties: {
    records: {
      type: 'array',
      items: {
        type: 'object',
        properties: {
          slug: { type: 'string' },
          aligned: { type: 'boolean' },
          blankLanguages: { type: 'array', items: { type: 'string' } },
          assignments: {
            type: 'array',
            items: {
              type: 'object',
              properties: {
                lang: { type: 'string' },
                value: { type: 'string' },
              },
              required: ['lang', 'value'],
            },
          },
          reason: { type: 'string' },
        },
        required: ['slug', 'aligned', 'reason'],
      },
    },
  },
  required: ['records'],
}

const BATCHES = ${JSON.stringify(batches, null, 2)}

phase('Align')

const results = await parallel(BATCHES.map((b) => () =>
  agent(
    \`Align language labels to name lists from the Ayurvedic Pharmacopoeia of India.

Each monograph below came out of OCR as two separate blocks: the language labels in the
order the Pharmacopoeia prints them, and the drug's names in the same order. The lists are
different lengths, which means one or more languages have NO name for this drug and the
gap is invisible from position alone.

Your job is to say which languages are blank, so the rest line up. This needs no web
research. The names are already the Pharmacopoeia's and are not in question; the only
question is which language each name is in.

WORKED EXAMPLE. Adhaki (Cajanus cajan), 15 labels and 14 names:
  labels: Sanskrit, Assamese, Bengali, English, Gujrati, Hindi, Kannada, Kashmiri,
          Malayalam, Marathi, Oriya, Punjabi, Tamil, Telugu, Urdu
  names:  Tuvari / Ruharmah / Adar, Aaharee, Arhar / Pigeon Pea, Red Gram /
          Tuvar, Tuvera, Tur, Tuver / Arahad, Arahar / Togari, Tovaree, Kari Uddu /
          Thuvara, Tuvara / Toor, Toori, Tura / Harada, Kandulagachha / Arhar /
          Tovarai, Thovary, Thuvarai / Kandulu, Kadulu / Arhar
The blank one is KASHMIRI: pigeonpea is not a Kashmiri crop, and "Thuvara, Tuvara" is
Malayalam, not Kashmiri. With Kashmiri blank, Malayalam takes Thuvara, Marathi takes Toor,
Oriya takes Kandulagachha (an Oriya form), Punjabi takes Arhar, Tamil takes Tovarai,
Telugu takes Kandulu, Urdu takes Arhar. Every row then fits its language.

HOW TO DECIDE. Use the script-independent cues that actually identify these languages:
  - Dravidian name shapes: Malayalam and Tamil forms of the same root differ predictably
    (Nellikka / Nellikkai), Kannada often ends -u or -gida, Telugu often -amu or -kaya.
  - Oriya forms frequently end -gachha; Bengali often shares the Sanskrit stem.
  - Urdu names are often Perso-Arabic (Khar-e-Khasak, Muqil, Tukhm-e-) and look unlike the
    Indic forms around them.
  - Kashmiri and Assamese are the languages most often blank, because many drugs are not
    traded or grown in those regions. Do not assume it, but check them first.
  - English names are descriptive binomial-ish phrases (Caltrops Fruit, Emblic Myrobalan)
    and are easy to place, which anchors everything before and after them.

MONOGRAPHS (batch \${b.id}):
\${b.records.map((r) => \`
[\${r.slug}]  \${r.heading} (\${r.part})  ->  \${r.title}
  labels (\${r.labels.length}): \${r.labels.join(', ')}
  names  (\${r.values.length}):
\${r.values.map((v, i) => \`    \${i}. \${v}\`).join('\\n')}
\`).join('\\n')}

For EACH monograph return:
  aligned          true only if you can place every name with confidence.
  blankLanguages   the labels you concluded have no name. Its length must equal
                   labels.length minus names.length.
  assignments      one entry per NAME, giving the language it belongs to and the name text
                   EXACTLY as printed above, unchanged. Do not reword, reorder within a
                   line, correct a spelling, or drop a variant.
  reason           which languages you judged blank and the cue that decided it. Concrete.

Set aligned = false when the evidence does not settle it, and say what is ambiguous. That
is a useful answer: these names stay unpublished and cost nothing, whereas a guessed
alignment publishes a Tamil name as Hindi on a reference page. Do not force an alignment
to avoid returning false.

If the name count EXCEEDS the label count, the OCR has pulled in a line that is not a name.
Set aligned = false and name the line you believe is intrusive.\`,
    { label: \`align:\${b.id}\`, phase: 'Align', schema: ALIGN_SCHEMA },
  ))).then((r) => r.filter(Boolean))

const records = results.flatMap((r) => r.records || [])
const ok = records.filter((r) => r.aligned && Array.isArray(r.assignments) && r.assignments.length)

// A returned alignment is only accepted if its own arithmetic holds: the languages it calls
// blank plus the names it placed must account for every label. An agent that says "aligned"
// while placing ten names against fifteen labels has not aligned anything.
const consistent = ok.filter((r) => {
  const src = BATCHES.flatMap((b) => b.records).find((x) => x.slug === r.slug)
  if (!src) return false
  const blanks = (r.blankLanguages || []).length
  return r.assignments.length === src.values.length
    && blanks === src.labels.length - src.values.length
})

log(\`batches returned \${results.length} of \${BATCHES.length}\`)
log(\`monographs adjudicated \${records.length}\`)
log(\`aligned \${ok.length}, of which arithmetically consistent \${consistent.length}\`)
log(\`declined as ambiguous \${records.length - ok.length}\`)

return {
  records,
  accepted: consistent,
  summary: {
    batchesExpected: BATCHES.length,
    batchesReturned: results.length,
    adjudicated: records.length,
    aligned: ok.length,
    accepted: consistent.length,
    rejectedForArithmetic: ok.length - consistent.length,
    declined: records.length - ok.length,
  },
}
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, script);

console.log(`monographs to adjudicate  ${todo.length}`);
console.log(`batches                   ${batches.length} at ${PER} each`);
console.log(`wrote                     ${OUT} (${(script.length / 1024).toFixed(0)} KB)`);
console.log(`\nRun it:  Workflow({ scriptPath: "${path.resolve(OUT)}" })`);
