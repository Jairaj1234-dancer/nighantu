#!/usr/bin/env node
/**
 * Take the editorial apparatus out of 54 answer blocks, where it is the meta description.
 *
 * THIS IS THE SAME DEFECT AS fix-answer-citations.mjs AND I SCOPED IT WRONG. That pass looked for
 * answers containing a markdown link, found 60, and fixed them. The frame was wrong: what leaked is
 * everything lib/claims.mjs writes into the cited-research section, and the link is only the part
 * that still looked like markup afterwards. Grepping for the leftovers after that pass turned up 54
 * more pages, none of which had ever held a link.
 *
 * WHAT IS LIVE RIGHT NOW, in two shapes.
 *
 * 49 pages end their meta description with claims.mjs shortfallNote, addressed to nobody:
 *
 *   Agnitundi Vati is a classical Ayurvedic vati, a herbal tablet or pill. Classical formulations
 *   are researched largely in journals that PubMed does not index, so an absence here reflects the
 *   reach of the index rather than the state of the evidence.
 *
 * It is a good note. It belongs on the page, under the heading it explains, which is where
 * claims.mjs puts it. In a search result it is an apology to a searcher for an absence they cannot
 * see, attached to a sentence that was supposed to tell them what the drug is.
 *
 * 5 pages print a raw PubMed esummary response:
 *
 *   Isabgol (Plantago ovata) is a plant drug, also called Snigdhajirakam and Isabagola. Total
 *   PubMed publications found: 122 Authors: Fugh-Berman A Journal: Lancet (London, England) (2000)
 *   PMID: 10675182 > Concurrent use of herbs may mimic, magnify, or oppose the effect of drugs.
 *
 * Same class as the four Python dicts on the hazardous pages: an API response serialised into the
 * sentence a searcher is shown. jamun's version carries "Keywords: Jamun, Syzygium cumin, diabetes
 * mellitus, hyperlipidemia, metabolic syndrome, obesity", which is a disease keyword list in a
 * meta description, and no gate in this repository was looking for a colon-labelled field dump.
 *
 * WHY IT LEAKED WITHOUT ANY MARKUP. The apparatus is emitted italicised, so it should have been
 * recognisable. answer.mjs called stripMarkup on the whole body and split the result into
 * sentences, so by the time anything was filtered the asterisks were already gone and a generated
 * note was indistinguishable from a sentence someone wrote. That ordering is fixed in answer.mjs:
 * the split now happens first and the apparatus is discarded while it is still marked as such.
 *
 * REMOVAL IS BY EXACT TEMPLATE, because these strings are generated by code in this repository and
 * can be quoted rather than guessed at. The dump is truncated at its own label, on the same
 * principle as the citation pass: the answer ends where the dump begins.
 *
 *   node scripts/fix-answer-apparatus.mjs            report what would change
 *   node scripts/fix-answer-apparatus.mjs --write    apply it
 *   node scripts/fix-answer-apparatus.mjs --verbose  every page, not the first six
 */
import fs from 'node:fs';
import path from 'node:path';
import { walk } from './lib.mjs';
import { answerViolations } from './lib/answer-safety.mjs';

const WRITE = process.argv.includes('--write');
const VERBOSE = process.argv.includes('--verbose');

/**
 * The exact sentences lib/claims.mjs shortfallNote emits. Quoted from that function rather than
 * described by a pattern: a template this repository writes is a known string, and matching a known
 * string cannot take a sentence an editor wrote with it.
 */
const TEMPLATES = [
  /\s*\d+ further claims? previously listed here could not be traced to a published paper and (?:has|have) been removed\./,
  /\s*An absence here means we could not identify the source, not that no work exists\./,
  /\s*Classical formulations are researched largely in journals that PubMed does not index, so an absence here reflects the reach of the index rather than the state of the evidence\./,
];

/** The label the esummary dump always opens with. Everything from here on is the response. */
const DUMP_AT = /\s*Total PubMed publications found:/;

const CITES = JSON.parse(fs.readFileSync(path.join('src', 'data', 'citations.json'), 'utf8')).pages;

/**
 * A JOURNAL NAME STRANDED AS A WHOLE SENTENCE, which claims.mjs emits italicised between a title
 * and a PMID. herb/vatagajankush-rasa ends "... of the rasa shastra tradition. Journal of Ayurveda
 * and integrative medicine." once the note around it is gone.
 *
 * Matched only against the journals in that page's own citation records, and only where the journal
 * is the ENTIRE sentence. Both constraints matter: an unanchored substring test for the journal
 * "Ayu" matches inside the word "Ayurvedic", which is on almost every page here.
 */
const journalSentences = (key) => (CITES[key]?.citations ?? [])
  .map((c) => c.journal)
  .filter(Boolean);

/**
 * A sentence opening in lower case and running to three words or fewer is wreckage.
 *
 * herb/sala reads "... Listed in the Ayurvedic Pharmacopoeia of India. coli 3 further claims
 * previously listed here ...": the composer split a findings line on the period in "E. coli" and
 * carried the second half in. Removing the template strands "coli". Real sentences on these pages
 * begin with a capital, and this runs only where a template actually matched, so there is known
 * wreckage rather than a guess.
 */
const isOrphan = (s) => /^[a-z]/.test(s.trim()) && s.trim().split(/\s+/).length <= 3;

const changed = [];
const refused = [];
let dumps = 0;
let notes = 0;

for (const rel of walk('content')) {
  const file = path.join('content', rel);
  const raw = fs.readFileSync(file, 'utf8');
  const m = /^answer:\s*"(.*?)"\s*$/m.exec(raw);
  if (!m) continue;

  const key = `${rel.split(path.sep)[0]}/${path.basename(rel, '.md')}`;
  let next = m[1];
  let touched = 0;

  const dumpAt = next.search(DUMP_AT);
  if (dumpAt !== -1) { next = next.slice(0, dumpAt); touched += 1; dumps += 1; }

  for (const t of TEMPLATES) {
    if (!t.test(next)) continue;
    next = next.replace(t, '');
    touched += 1;
    notes += 1;
  }
  if (!touched) continue;

  const journals = journalSentences(key);
  next = next
    .split(/(?<=[.!?])\s+/)
    .filter((s) => !isOrphan(s))
    .filter((s) => !journals.some((j) => s.trim().replace(/\.$/, '') === j))
    .join(' ')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/[\s,;:]+$/, '');
  if (next && !/[.!?]$/.test(next)) next += '.';

  // REFUSE RATHER THAN PUBLISH A FAULT, on the same terms as the citation pass.
  if (next.includes('"')) { refused.push([key, 'quote would break frontmatter']); continue; }
  if (next.length < 40) { refused.push([key, `only ${next.length} characters survive: this answer was all apparatus`]); continue; }
  const v = answerViolations(next);
  if (v.length) { refused.push([key, `violates after removal: ${JSON.stringify(v)}`]); continue; }

  changed.push({ key, before: m[1], after: next });
  if (WRITE) fs.writeFileSync(file, raw.replace(m[0], `answer: "${next}"`));
}

const lens = changed.map((c) => c.after.length).sort((a, b) => a - b);
console.log(`${changed.length} answers cleaned, ${refused.length} refused.`);
console.log(`${notes} generated notes removed, ${dumps} PubMed response dumps truncated.`);
if (lens.length) console.log(`surviving answers are ${lens[0]} to ${lens[lens.length - 1]} characters, median ${lens[Math.floor(lens.length / 2)]}.`);
console.log();

for (const c of (VERBOSE ? changed : changed.slice(0, 6))) {
  console.log(`  ${c.key}`);
  console.log(`    was: ${c.before.slice(0, 200)}`);
  console.log(`    now: ${c.after}`);
  console.log();
}

if (refused.length) {
  console.log('REFUSED, nothing written for these:');
  for (const [k, why] of refused) console.log(`   ${k}  ${why}`);
}
if (!WRITE) console.log('\nDry run. Nothing written. Re-run with --write to apply.');
