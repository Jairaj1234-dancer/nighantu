#!/usr/bin/env node
/**
 * Generate workflows/verify-names.js with the candidate batches embedded in the script.
 *
 * Why generated rather than parameterised. Workflow scripts have no filesystem access, so a
 * workflow cannot read data/name-candidates.json itself; the payload has to arrive in the
 * script or through `args`. At 638 candidates the batch payload runs past the size where
 * passing it through `args` is comfortable, and an embedded payload has a second advantage
 * that matters more: the script is then a complete record of exactly what was checked, so a
 * resumed or re-run verification is checking the same thing.
 *
 * Batched by PAGE, not by candidate. Every name for one plant resolves from a single
 * retrieval of that plant's vernacular names, so grouping by page turns ~45 separate lookups
 * per agent into about 18. Batching by candidate would re-retrieve the same plant five times.
 *
 *   node scripts/build-verify-names.mjs            # default 18 pages per agent
 *   node scripts/build-verify-names.mjs --per 24
 */
import fs from 'node:fs';
import path from 'node:path';

const IN = path.join('data', 'name-candidates.json');
const OUT = path.join('workflows', 'verify-names.js');

const PER = (() => {
  const i = process.argv.indexOf('--per');
  return i === -1 ? 18 : Math.max(1, Number(process.argv[i + 1]));
})();

const payload = JSON.parse(fs.readFileSync(IN, 'utf8'));

// Group candidates by the page they would land on.
const pages = new Map();
for (const c of payload.candidates) {
  const key = `${c.kind}/${c.slug}`;
  if (!pages.has(key)) {
    pages.set(key, {
      key, kind: c.kind, slug: c.slug, title: c.title,
      botanical: c.botanical, wikidata: c.wikidata, names: [],
    });
  }
  pages.get(key).names.push({ lang: c.lang, langName: c.langName, name: c.name, iast: c.iast });
}

const list = [...pages.values()].sort((a, b) => a.key.localeCompare(b.key));
const batches = [];
for (let i = 0; i < list.length; i += PER) {
  batches.push({ id: `b${String(batches.length + 1).padStart(2, '0')}`, pages: list.slice(i, i + PER) });
}

const totalNames = list.reduce((a, p) => a + p.names.length, 0);

const script = `export const meta = {
  name: 'verify-indic-names',
  description: 'Corroborate harvested Hindi, Sanskrit and Tamil plant names against named independent sources',
  phases: [
    { title: 'Corroborate', detail: 'one agent per batch of pages; every candidate name checked against a second source' },
  ],
}

/**
 * GENERATED by scripts/build-verify-names.mjs. Do not hand-edit; regenerate.
 *
 * ${batches.length} batches, ${list.length} pages, ${totalNames} candidate names harvested from Wikidata.
 *
 * The check that matters is not "does this name exist". It is "does this name denote THIS
 * plant". Wikidata fails that specific check in this dataset: it lists aśvattha, which is
 * Ficus religiosa, as a Sanskrit alias for both Adhatoda vasica and Aegle marmelos. A
 * verifier that only confirmed the string was a real Sanskrit plant name would pass both.
 */

const VERDICT_SCHEMA = {
  type: 'object',
  properties: {
    verdicts: {
      type: 'array',
      items: {
        type: 'object',
        properties: {
          slug: { type: 'string' },
          lang: { type: 'string' },
          name: { type: 'string' },
          confirmed: { type: 'boolean' },
          corroboratingSource: { type: 'string' },
          denotesInstead: { type: 'string' },
          preferred: { type: 'boolean' },
          reason: { type: 'string' },
        },
        required: ['slug', 'lang', 'name', 'confirmed', 'reason'],
      },
    },
    discovered: {
      type: 'array',
      items: {
        type: 'object',
        properties: {
          slug: { type: 'string' },
          lang: { type: 'string' },
          name: { type: 'string' },
          source: { type: 'string' },
          reason: { type: 'string' },
        },
        required: ['slug', 'lang', 'name', 'source'],
      },
    },
  },
  required: ['verdicts'],
}

const BATCHES = ${JSON.stringify(batches, null, 2).replace(/\n/g, '\n')}

phase('Corroborate')

const results = await parallel(BATCHES.map((b) => () =>
  agent(
    \`Corroborate candidate Indic names for Ayurvedic plant monographs. Your default is NOT
CONFIRMED. You exist to keep wrong names off a botanical reference, not to approve a list.

These names were harvested from Wikidata labels and aliases. Wikidata is unreliable for
vernacular plant names and this dataset already contains a proven error: it lists
"अश्वत्थः" (aśvattha) as a Sanskrit alias for BOTH Adhatoda vasica AND Aegle marmelos.
Aśvattha is Ficus religiosa and is neither of them. That is the exact failure you are here
to catch, and it will appear in your batch.

PAGES AND CANDIDATE NAMES (batch \${b.id}):
\${b.pages.map((p) => \`
[\${p.slug}]  \${p.title}
  botanical: \${p.botanical}
  wikidata:  \${p.wikidata}
  candidates:
\${p.names.map((n) => \`    - \${n.langName} (\${n.lang}): "\${n.name}"\${n.iast ? \` [IAST \${n.iast}]\` : ''}\`).join('\\n')}
\`).join('\\n')}

METHOD. For each PAGE, first retrieve that plant's vernacular names from sources independent
of Wikidata, then judge each candidate against what you retrieved. Retrieve, do not recall:
a name you are reconstructing from memory is exactly how a misidentification propagates.

Use sources that publish names per botanical species, and name the one you used:
  - Ayurvedic Pharmacopoeia of India (API) and Ayurvedic Formulary of India (AFI), which give
    official Sanskrit and regional names per monograph. Strongest source for Sanskrit.
  - eNighantu / CCRAS portals.
  - IMPPAT (IIT Madras), which lists vernacular names per species.
  - India Biodiversity Portal; Plants of the World Online (Kew) for accepted botanical names
    and synonymy.
  - A language Wikipedia is a WEAK corroborator because it often mirrors Wikidata. If it is
    all you have, say so in the reason and do not set confirmed.

For EACH candidate name return:
  confirmed            true only if an independent named source attests this name for THIS
                       species. Absent corroboration means false, not "probably fine".
  corroboratingSource  the specific source and what it said. Required when confirmed.
  denotesInstead       THE FIELD THAT MATTERS MOST. If the name is a genuine plant name but
                       for a DIFFERENT species, put that species here. A name that is merely
                       unattested is harmless once dropped. A name that correctly belongs to
                       another plant is a botanical error that would survive on the page and
                       mislead a reader, so flag it explicitly.
  preferred            true for the single best-known form in that language, the one a
                       speaker would most likely use or search. At most one per language per
                       page; leave false if you cannot tell.
  reason               what you retrieved and what you concluded. Concrete.

Also return \\\`discovered\\\`: names an authoritative source gives for this species in Hindi,
Sanskrit or Tamil that are NOT in the candidate list. Give the source for each. These are
worth more than the harvested set because they come from the authority directly. Do not pad
this; only names you actually read in a source you name.

Script matters: give Hindi and Sanskrit in Devanagari and Tamil in Tamil script, as the
candidates are. Do not transliterate into Latin, that is generated separately.\`,
    { label: \`names:\${b.id}\`, phase: 'Corroborate', schema: VERDICT_SCHEMA },
  ))).then((r) => r.filter(Boolean))

const verdicts = results.flatMap((r) => r.verdicts || [])
const discovered = results.flatMap((r) => r.discovered || [])
const confirmed = verdicts.filter((v) => v.confirmed)
const misattributed = verdicts.filter((v) => !v.confirmed && v.denotesInstead)

log(\`batches returned \${results.length} of \${BATCHES.length}\`)
log(\`checked \${verdicts.length} candidate names\`)
log(\`confirmed \${confirmed.length} (\${verdicts.length ? Math.round((confirmed.length / verdicts.length) * 100) : 0}%)\`)
log(\`misattributed to another species: \${misattributed.length}\`)
log(\`discovered in authoritative sources: \${discovered.length}\`)

return {
  verdicts,
  discovered,
  summary: {
    batchesExpected: BATCHES.length,
    batchesReturned: results.length,
    checked: verdicts.length,
    confirmed: confirmed.length,
    rejected: verdicts.length - confirmed.length,
    misattributed: misattributed.length,
    discovered: discovered.length,
    byLang: ['hi', 'sa', 'ta'].reduce((a, l) => {
      a[l] = { checked: verdicts.filter((v) => v.lang === l).length, confirmed: confirmed.filter((v) => v.lang === l).length }
      return a
    }, {}),
  },
}
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, script);

console.log(`pages          ${list.length}`);
console.log(`candidates     ${totalNames}`);
console.log(`batches        ${batches.length} at ${PER} pages each`);
console.log(`wrote          ${OUT} (${(script.length / 1024).toFixed(0)} KB)`);
console.log(`\nRun it:  Workflow({ scriptPath: "${path.resolve(OUT)}" })`);
