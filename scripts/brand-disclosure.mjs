#!/usr/bin/env node
/**
 * Turn the brand survey into the few facts a published comparison may state, and keep the page's
 * tables tied to them.
 *
 * WHY THIS SITS BETWEEN THE SURVEY AND THE PAGE. data/brands/ holds 520 KB of other companies'
 * product text, the quantity figures parsed out of it, their dose wording and a per-host read on
 * their crawler posture. That is gitignored and stays that way: this repository is public and is
 * the wrong place for a file of that shape. What a reader needs, and all the page states, is much
 * smaller and is a different kind of claim.
 *
 * WHAT THE PAGE IS ALLOWED TO SAY, and the line this script draws.
 *
 * It states, per company and per preparation, whether that company's own product page published
 * an ingredient list, a list with a quantity against each ingredient, or neither, on the date it
 * was read. That is directly observable, it is falsifiable by anyone who opens the page, and it is
 * a fact about disclosure rather than about the product.
 *
 * It does NOT restate anybody's figures. The collector does parse them, and the parse is good
 * enough to have overturned the premise this page started from, but it is not perfect: on
 * Patanjali's Chyawanprash the "Each 100 g" basis row is counted as an ingredient quantity
 * because the basis detector did not fire on that layout. A figure mis-attributed to a named
 * company is the one error a page like this cannot afford, so no figure of theirs is printed and
 * nothing here depends on the parse being right. Whether a quantity is present at all survives
 * that doubt: a page either has numbers against its ingredients or it does not.
 *
 * It also does not reproduce their wording, which keeps the licence question from arising at all.
 *
 * AGGREGATION. 26 of the 157 company-and-preparation pairs have more than one page, usually a
 * pack-size or combo variant. Two of them disagree with themselves, so a cell carries the best
 * state observed AND the count: "quantities, on 5 of 7 pages" is the honest reading of a company
 * that publishes fully on its single-pack pages and not on one combo listing.
 *
 * THREE MODES.
 *
 *   node scripts/brand-disclosure.mjs            reads data/brands/, writes src/data/brand-disclosure.json
 *                                                and injects the tables into the page
 *   node scripts/brand-disclosure.mjs --render   reads only the committed JSON, injects the tables
 *   node scripts/brand-disclosure.mjs --check    as --render, but fails instead of writing
 *
 * The split matters because data/brands/ is gitignored, so CI has only the committed JSON. CI runs
 * --check, which is what keeps the page's tables from drifting away from the measurement they
 * claim to report.
 */
import fs from 'node:fs';
import path from 'node:path';

const RENDER_ONLY = process.argv.includes('--render');
const CHECK = process.argv.includes('--check');

const SURVEY = path.join('data', 'brands');
const OUT = path.join('src', 'data', 'brand-disclosure.json');
const PAGE = path.join('content', 'choosing', 'who-publishes-the-composition.md');
const COMPOSITION = path.join('src', 'data', 'composition.json');

const BEGIN = '<!-- BEGIN generated by scripts/brand-disclosure.mjs -->';
const END = '<!-- END generated by scripts/brand-disclosure.mjs -->';

/** A preparation enters the per-preparation table only where enough companies sell it to compare. */
const MIN_COMPANIES = 3;

// --------------------------------------------------------------------------- measure
if (!RENDER_ONLY && !CHECK) {
  if (!fs.existsSync(SURVEY)) {
    console.error(`${SURVEY} is absent. Run scripts/brand-catalogue.mjs first, or pass --render to`);
    console.error('rebuild the page from the committed measurement.');
    process.exit(1);
  }
  const products = JSON.parse(fs.readFileSync(path.join(SURVEY, 'products.json'), 'utf8'));
  const discovery = JSON.parse(fs.readFileSync(path.join(SURVEY, 'discovery.json'), 'utf8'));
  /**
   * Wave 2, the whole product range, read separately and kept separate.
   *
   * Wave 1 identifies a product by matching its URL slug against the formulary names, which is
   * the right way to fetch nothing on the chance it might be relevant, and which makes the result
   * a measurement of each company's CLASSICAL range. Stated without that qualification it reads
   * as a fact about the company, and for two companies it is materially different: Patanjali
   * documents 91% of its formulary-name pages and 54% of its whole range, Zandu 100% of three and
   * 77% of 134.
   *
   * So both populations publish, side by side, and the page says which is which. Collapsing them
   * to one number would lose a real difference in both directions, and restating only one
   * company on the better-sampled population, ours, would be the self-serving move the page's
   * whole disclosure discipline exists to prevent.
   */
  const w2Path = path.join(SURVEY, 'products-wave2.json');
  const wave2 = fs.existsSync(w2Path) ? JSON.parse(fs.readFileSync(w2Path, 'utf8')) : null;
  const afi = JSON.parse(fs.readFileSync(COMPOSITION, 'utf8')).records;

  /**
   * The site's own name for each preparation, read from the page it already publishes.
   *
   * The formulary's entry heading is its transliteration without diacritics: "Cyavanaprasa",
   * "Asokarista", "Parthadyarista (Synonym : Arjunarista)". That is the right thing to cite and
   * the wrong thing to head a row with, because nobody searches for it and a reader holding a jar
   * of Chyawanprash would not recognise it. So the row is headed with the title of our own
   * formulation page and the formulary heading travels in the entry column, where it belongs.
   */
  const titleOf = (slug) => {
    const f = path.join('content', 'formulation', `${slug}.md`);
    if (!fs.existsSync(f)) return null;
    const m = fs.readFileSync(f, 'utf8').match(/^title:\s*"?([^"\n]+)"?/m);
    return m ? m[1].trim() : null;
  };

  /**
   * What a single page shows. `unreadable` is kept apart from `absent` upstream and stays apart
   * here, because only `absent` is a claim about the company: a page that served almost no text
   * renders client-side, which is a fact about their stack. Nothing in this survey came back
   * unreadable in the end, and the state is still carried so a future run cannot quietly merge it.
   */
  const stateOf = (p) => {
    const s = (p.composition ?? {}).state;
    if (s !== 'found') return s === 'unreadable' ? 'unreadable' : 'neither';
    return p.quantityCount > 0 ? 'quantities' : 'list';
  };
  const RANK = { quantities: 3, list: 2, neither: 1, unreadable: 0 };

  /**
   * Why a company contributed no measured page. Each of these is a finding rather than a gap, and
   * the page says so: a catalogue no answer engine may read is a catalogue no answer engine can
   * cite for its own products.
   */
  const accessOf = (b, measured, rangeMeasured) => {
    if (b.robots?.verdict === 'rules' && b.allowed && b.allowed['/products/'] === false) {
      return 'its robots.txt declines this crawler, and declines every AI crawler tested except Googlebot, so nothing was fetched';
    }
    if (!b.catalogueReadable || b.pages === 0) return 'no readable sitemap was found, so its catalogue could not be enumerated';
    /**
     * A readable sitemap with no individual product page in it, which is a different finding from
     * having no sitemap and from publishing no composition.
     *
     * Nagarjuna Herbal Concentrates lists 298 pages and not one is a product: the catalogue is
     * reached through category listings only. So there is no page for any single product of theirs
     * to publish a composition ON, and no answer engine can cite them for one. Recording this as
     * "publishes nothing" would be wrong in a way that matters: the company has not declined to
     * state a composition, it has not published a page where a composition would go.
     */
    if ((b.pages ?? 0) > 0 && !(b.candidates ?? []).length) {
      return 'its sitemap is readable and lists no individual product page at all, only category '
        + 'listings, so there is no product page of theirs for a composition to appear on';
    }
    /**
     * Wave 2 split this case in two, and the distinction matters to the company.
     *
     * Before it, "carried no product under a formulary name" was the end of the sentence and the
     * company sat in a list of companies we could say nothing about. Two companies were in it,
     * and one of them, Charak Pharma, turns out to document 1 of its 113 product pages. That is a
     * measured fact about a named company and it belongs in the table, not in a footnote about
     * our own name list.
     */
    if (!measured && rangeMeasured) {
      return 'read in full: its catalogue carried no product under any of the formulary names '
        + 'looked for, so it has no formulary-name figures, and its whole range was read instead';
    }
    if (!measured) return 'its catalogue was readable and carried no product under any of the formulary names looked for';
    return 'allowed by its robots.txt and read';
  };

  const companies = [];
  const perPrep = new Map();

  for (const b of discovery.brands) {
    const mine = products.products.filter((p) => p.brand === b.id);
    const w2All = wave2 ? wave2.products.filter((p) => p.brand === b.id) : [];
    const w2Mine = w2All.filter((p) => p.outcome === 'read');
    const byPrep = new Map();
    for (const p of mine) {
      if (!byPrep.has(p.formulation)) byPrep.set(p.formulation, []);
      byPrep.get(p.formulation).push(p);
    }

    companies.push({
      id: b.id,
      name: b.name,
      origin: b.origin,
      ours: Boolean(b.ours),
      access: accessOf(b, mine.length, w2Mine.length),
      pagesInCatalogue: b.pages ?? 0,
      // The formulary-name population: wave 1.
      pagesMeasured: mine.length,
      pagesWithQuantities: mine.filter((p) => stateOf(p) === 'quantities').length,
      pagesWithListOnly: mine.filter((p) => stateOf(p) === 'list').length,
      pagesWithNeither: mine.filter((p) => stateOf(p) === 'neither').length,
      pagesUnreadable: mine.filter((p) => stateOf(p) === 'unreadable').length,
      preparationsSold: byPrep.size,
      // The whole range: wave 2. Null where wave 2 has not read this company at all.
      range: w2Mine.length ? {
        pagesRead: w2Mine.length,
        pagesAttempted: w2All.length,
        pagesWithQuantities: w2Mine.filter((p) => stateOf(p) === 'quantities').length,
        pagesWithListOnly: w2Mine.filter((p) => stateOf(p) === 'list').length,
        pagesWithNeither: w2Mine.filter((p) => stateOf(p) === 'neither').length,
        pagesUnreadable: w2Mine.filter((p) => stateOf(p) === 'unreadable').length,
        pagesStatingADose: w2Mine.filter((p) => (p.dose ?? {}).state === 'found').length,
        pagesCitingTheFormulary: w2Mine.filter((p) => (p.authorities ?? []).some((a) => a.id === 'afi')).length,
        pagesCitingAnyAuthority: w2Mine.filter((p) => (p.authorities ?? []).length > 0).length,
      } : null,
    });

    for (const [slug, pages] of byPrep) {
      if (!perPrep.has(slug)) perPrep.set(slug, new Map());
      const best = pages.map(stateOf).sort((x, y) => RANK[y] - RANK[x])[0];
      perPrep.get(slug).set(b.id, {
        state: best,
        pages: pages.length,
        pagesInThatState: pages.filter((p) => stateOf(p) === best).length,
        // Their own public product page, so a company checking this knows which one was read.
        urls: pages.map((p) => p.url),
        readOn: pages.map((p) => String(p.fetchedAt ?? '').slice(0, 10)).sort()[0] ?? null,
      });
    }
  }

  const preparations = [...perPrep.entries()]
    .filter(([, byCo]) => byCo.size >= MIN_COMPANIES)
    .map(([slug, byCo]) => {
      const entry = afi[slug];
      const rows = (entry?.rows ?? []).filter((r) => !r.structural);
      return {
        slug,
        name: titleOf(slug) ?? entry?.entryHeading ?? slug,
        formularyHeading: entry?.entryHeading ?? null,
        page: `/formulation/${slug}/`,
        afiPart: entry?.afiPart ?? null,
        entryNumber: entry?.entryNumber ?? null,
        ingredientCount: rows.length,
        ingredientsWithAQuantity: rows.filter((r) => r.quantity).length,
        companies: Object.fromEntries([...byCo.entries()].sort(([a], [b]) => a.localeCompare(b))),
      };
    })
    .sort((a, b) => Object.keys(b.companies).length - Object.keys(a.companies).length
      || a.slug.localeCompare(b.slug));

  const payload = {
    note: 'What each company published on its own product pages, as those pages were served to '
      + 'this crawler on the date recorded. A state of "neither" means the page carried substantial '
      + 'readable text and no ingredient list in it. No figure published by any company is '
      + 'restated here, and no wording of theirs is reproduced. See the page named in `page` for '
      + 'what this is for and what it does not measure.',
    page: '/choosing/who-publishes-the-composition/',
    measuredOn: products.collectedOn,
    agent: products.agent,
    measuringStick: 'src/data/composition.json, this project\'s transcription of the Ayurvedic '
      + 'Formulary of India, checked row by row against the book and cited to part and entry number.',
    minCompaniesForAPreparationRow: MIN_COMPANIES,
    /**
     * The method's own limits, measured rather than asserted. Each of these is something the page
     * says about itself, and each was a guess until wave 2.
     */
    wholeRange: wave2 ? {
      measuredOn: wave2.collectedOn,
      pagesAttempted: wave2.products.length,
      pagesRead: wave2.products.filter((p) => p.outcome === 'read').length,
      // All transient: timeouts and failed connections across three hosts, no refusals.
      pagesThatCouldNotBeRead: wave2.products.filter((p) => p.outcome !== 'read').length,
      pagesRenderingClientSide: wave2.products.filter((p) => p.outcome === 'read' && stateOf(p) === 'unreadable').length,
      pagesStatingADose: wave2.products.filter((p) => p.outcome === 'read' && (p.dose ?? {}).state === 'found').length,
      pagesNamingIngredients: wave2.products.filter((p) => p.outcome === 'read' && (p.composition ?? {}).state === 'found').length,
      pagesCitingTheFormulary: wave2.products.filter((p) => p.outcome === 'read' && (p.authorities ?? []).some((a) => a.id === 'afi')).length,
      pagesCitingAnyAuthority: wave2.products.filter((p) => p.outcome === 'read' && (p.authorities ?? []).length > 0).length,
      /**
       * How much the slug matcher missed, which was the other thing wave 2 existed to find out.
       * The matcher is re-run against each page's own TITLE on the pages whose URL slug it did
       * not match: a different spelling of the same name, written by the same company. 18 hits
       * across 2,769 unmatched pages, so wave 1's sample was not quietly missing a classical
       * range. See scripts/brand-wave2-report.mjs, which is where that is computed.
       */
      slugMatcherMissesFoundByTitle: 18,
      pagesWithNoFormularyNameInTheSlug: wave2.products.filter((p) => p.outcome === 'read' && !p.matchedByName).length,
    } : null,
    companies: companies.sort((a, b) => b.pagesMeasured - a.pagesMeasured || a.name.localeCompare(b.name)),
    preparations,
  };

  fs.writeFileSync(OUT, `${JSON.stringify(payload, null, 2)}\n`);
  console.log(`companies surveyed          ${payload.companies.length}`);
  console.log(`companies with pages read   ${payload.companies.filter((c) => c.pagesMeasured).length}`);
  console.log(`product pages measured      ${payload.companies.reduce((a, c) => a + c.pagesMeasured, 0)}`);
  console.log(`preparations compared       ${preparations.length} (sold by ${MIN_COMPANIES} or more of them)`);
  console.log(`wrote ${OUT}`);
}

// --------------------------------------------------------------------------- render
const data = JSON.parse(fs.readFileSync(OUT, 'utf8'));
const byId = Object.fromEntries(data.companies.map((c) => [c.id, c]));
const nameOf = (id) => byId[id]?.name ?? id;
const esc = (s) => String(s).replace(/\|/g, '\\|');

/** Companies in a given state for one preparation, named in a stable order and never ranked. */
const inState = (prep, state) => Object.entries(prep.companies)
  .filter(([, v]) => v.state === state)
  .map(([id, v]) => {
    const name = nameOf(id);
    const partial = v.pages > 1 && v.pagesInThatState < v.pages
      ? ` (on ${v.pagesInThatState} of its ${v.pages} pages)` : '';
    return `${name}${partial}`;
  })
  .sort((a, b) => a.localeCompare(b));

const lines = [];

/**
 * One table per population, the same shape in both, so a reader can set them beside each other.
 *
 * The "neither" and "could not be read" columns stay apart, because only the first is a claim
 * about the company. The page said nothing in the survey had landed in the second; wave 2 found
 * ten pages that do, all on one host, so the column is now real and is shown.
 */
const stateCols = '| Company | Product pages read | Ingredients and quantities | Ingredient list only | Neither | Could not be read |';
const stateRule = '| --- | --- | --- | --- | --- | --- |';

/**
 * One row order, used by BOTH tables, so they can be read side by side.
 *
 * Sorting each table by its own size would reorder the rows between them and make the comparison
 * the tables exist for into a puzzle. Ordered by the size of the range read, which is a fact about
 * the survey rather than a judgement about the company.
 */
const inRangeOrder = data.companies.filter((x) => x.range)
  .sort((a, b) => b.range.pagesRead - a.range.pagesRead);

lines.push('### Everything each company sells', '');
lines.push('The whole product range on each host that permitted it, classical and proprietary alike.',
  'This is the figure that is a fact about the company.', '');
// Wrapped so six columns scroll at phone width rather than squeezing. The blank lines are
// load-bearing: without them remark treats the table as raw HTML and never renders it.
lines.push('<div class="tablewrap wide-table">', '');
lines.push(stateCols, stateRule);
for (const c of inRangeOrder) {
  const r = c.range;
  lines.push(`| ${esc(c.name)}${c.ours ? ' (ours)' : ''} | ${r.pagesRead} `
    + `| ${r.pagesWithQuantities} | ${r.pagesWithListOnly} | ${r.pagesWithNeither} | ${r.pagesUnreadable} |`);
}
lines.push('', '</div>', '');

lines.push('### Only the products sold under a formulary name', '');
lines.push('The same companies, counting only products whose name is one of the 101 formulary entries',
  'transcribed on this site. This is the figure that bears on whether a product can be checked',
  'against the entry it claims, and for two companies it is markedly higher than the first table.', '');
lines.push('<div class="tablewrap wide-table">', '');
lines.push(stateCols, stateRule);
for (const c of inRangeOrder) {
  if (!c.pagesMeasured) {
    lines.push(`| ${esc(c.name)}${c.ours ? ' (ours)' : ''} | none: sells nothing under a formulary name | | | | |`);
    continue;
  }
  lines.push(`| ${esc(c.name)}${c.ours ? ' (ours)' : ''} | ${c.pagesMeasured} `
    + `| ${c.pagesWithQuantities} | ${c.pagesWithListOnly} | ${c.pagesWithNeither} | ${c.pagesUnreadable} |`);
}
lines.push('', '</div>', '');

const noPages = data.companies.filter((c) => c.pagesMeasured === 0 && !c.range);
if (noPages.length) {
  const WORDS = ['no', 'One', 'Two', 'Three', 'Four', 'Five', 'Six', 'Seven', 'Eight'];
  lines.push(`${WORDS[noPages.length] ?? noPages.length} further compan${noPages.length === 1 ? 'y was' : 'ies were'} surveyed and`,
    'contributed no measured page. Each reason is itself a finding.', '');
  for (const c of noPages) lines.push(`- **${esc(c.name)}**: ${esc(c.access)}.`);
  lines.push('');
}

lines.push('### What each company published, by preparation', '');
lines.push('Only the preparations sold under a formulary name by three or more of the companies read,');
lines.push(`which is ${data.preparations.length} of them. The second column is the formulary entry itself, as transcribed`);
lines.push('and published on this site, which is the thing any of these products can be checked against.', '');
lines.push('<div class="tablewrap wide-table">', '');
lines.push('| Preparation | The formulary entry | Publishes ingredients and quantities | Publishes an ingredient list only | Publishes neither |');
lines.push('| --- | --- | --- | --- | --- |');
for (const p of data.preparations) {
  const addr = [p.afiPart && `Part ${p.afiPart}`, p.entryNumber].filter(Boolean).join(', ');
  const counts = `${p.ingredientCount} ingredients, `
    + (p.ingredientsWithAQuantity === p.ingredientCount
      ? 'a quantity for every one'
      : `a quantity for ${p.ingredientsWithAQuantity}`);
  // The heading stays in the book's own capitals, as /afi/ prints it: this column is a citation.
  const stick = [addr && `**${esc(addr)}**`, p.formularyHeading && esc(p.formularyHeading), counts]
    .filter(Boolean).join('. ');
  const cell = (s) => {
    const xs = inState(p, s);
    return xs.length ? esc(xs.join('; ')) : 'none';
  };
  lines.push(`| [${esc(p.name)}](${p.page}) `
    + `| ${stick} | ${cell('quantities')} | ${cell('list')} | ${cell('neither')} |`);
}
lines.push('', '</div>', '');
lines.push(`Every cell was read on ${data.measuredOn}. "None" means no company read here was in that`);
lines.push('state for that preparation, not that the preparation lacks the figure.');

const block = [BEGIN, '', ...lines, '', END].join('\n');

const current = fs.readFileSync(PAGE, 'utf8');
const begin = current.indexOf(BEGIN);
const end = current.indexOf(END);
if (begin < 0 || end < 0) {
  console.error(`${PAGE} has no generated block. Add these two lines where the tables belong:`);
  console.error(`  ${BEGIN}`);
  console.error(`  ${END}`);
  process.exit(1);
}
const next = current.slice(0, begin) + block + current.slice(end + END.length);

/**
 * THE PROSE FIGURES, which the generated block does not cover and which are the real drift risk.
 *
 * The tables are injected and `--check` already fails if they disagree with the measurement. The
 * hand-written prose around them carries 42 distinct figures: "2,979 product pages", "2,406 state
 * a dose", "18 of them", "ten pages on one host". Those are typed by a person, and the way this
 * page goes quietly wrong is that the survey is re-run, the tables update themselves, and a
 * sentence three paragraphs down still states last month's total about a named company.
 *
 * So each load-bearing total must appear SOMEWHERE in the prose. If the measurement moves and the
 * sentence was not rewritten, the new value is absent and this fails. It does not prove the
 * sentence is right, which no check can; it proves the sentence was revisited.
 *
 * Small numbers are matched as digits or as words, because "fourteen pages" reads better than
 * "14 pages" and the prose should not be bent to suit the gate.
 */
const WORD = ['zero', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine', 'ten',
  'eleven', 'twelve', 'thirteen', 'fourteen', 'fifteen', 'sixteen', 'seventeen', 'eighteen',
  'nineteen', 'twenty'];

const proseOf = (text) => {
  const b = text.indexOf(BEGIN);
  const e = text.indexOf(END);
  return b < 0 || e < 0 ? text : text.slice(0, b) + text.slice(e + END.length);
};

const figureChecks = () => {
  const w = data.wholeRange;
  const read = data.companies.filter((c) => c.range).length;
  const checks = [
    ['companies whose pages were read', read],
    ['companies surveyed', data.companies.length],
    ['preparations compared', data.preparations.length],
  ];
  if (w) {
    checks.push(
      ['pages read across the whole range', w.pagesRead],
      ['pages attempted', w.pagesAttempted],
      ['pages that could not be read', w.pagesThatCouldNotBeRead],
      ['pages rendering client-side', w.pagesRenderingClientSide],
      ['pages stating a dose', w.pagesStatingADose],
      ['pages naming ingredients', w.pagesNamingIngredients],
      ['pages citing the formulary', w.pagesCitingTheFormulary],
      ['pages citing any authority', w.pagesCitingAnyAuthority],
      ['pages with no formulary name in the slug', w.pagesWithNoFormularyNameInTheSlug],
      ['slug-matcher misses found by title', w.slugMatcherMissesFoundByTitle],
    );
  }
  return checks;
};

if (CHECK) {
  if (next !== current) {
    console.error(`FAIL: ${PAGE} does not match ${OUT}.`);
    console.error('Run `node scripts/brand-disclosure.mjs --render` and commit the result.');
    process.exit(1);
  }

  const prose = proseOf(current);
  const missing = [];
  for (const [label, value] of figureChecks()) {
    const forms = [String(value), Number(value).toLocaleString('en-GB')];
    if (value <= 20) forms.push(WORD[value]);
    if (!forms.some((f) => new RegExp(`(?<![\\w,.])${f.replace(/[.*+?^$()|[\]\\]/g, '\\$&')}(?![\\w%])`, 'i').test(prose))) {
      missing.push(`${label}: ${forms[1]} appears nowhere in the prose`);
    }
  }
  if (missing.length) {
    console.error(`FAIL: ${missing.length} figure(s) from the measurement are absent from the page's prose.`);
    console.error('The survey has moved and the sentences around the tables have not. Each of these');
    console.error('needs a sentence that states it, or a sentence that no longer should be there:');
    for (const m of missing) console.error(`  ${m}`);
    process.exit(1);
  }
  console.log(`prose figures      ${figureChecks().length} load-bearing totals all present`);
  console.log(`${PAGE} agrees with ${OUT}: ${data.preparations.length} preparations, `
    + `${data.companies.filter((c) => c.pagesMeasured).length} companies, measured ${data.measuredOn}.`);
  process.exit(0);
}

fs.writeFileSync(PAGE, next);
if (next !== current) console.log(`updated the generated tables in ${PAGE}`);
else console.log(`${PAGE} was already current`);
